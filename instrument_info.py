class InstrumentInfo:
    """Описание торгового инструмента (облигации, IRS и т.п.).

    Хранит имя инструмента и его идентификаторы во внешних системах.
    """

    def __init__(self, name, mdh_name, ps_name):
        """
        Args:
            name: внутреннее имя инструмента.
            mdh_name: альтернативный идентификатор инструмента во внешней системе
                (назначение пока не определено).
            ps_name: альтернативный идентификатор инструмента во внешней системе
                (назначение пока не определено).
        """
        self.name = name
        self.mdh_name = mdh_name
        self.ps_name = ps_name
